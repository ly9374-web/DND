"""Exercise real toast hit targets, cancellation and chat while generating."""
import re
from playwright.sync_api import expect, sync_playwright

URL = "http://127.0.0.1:8572"
with sync_playwright() as p:
    browser = p.chromium.launch(headless=True)
    page = browser.new_page(viewport={"width": 1440, "height": 1000})
    errors = []
    page.on("pageerror", lambda error: errors.append(str(error)))
    page.goto(URL)
    page.wait_for_load_state("networkidle")
    quick = page.locator('.dnd-quick-generation')
    expect(quick).to_be_visible(timeout=15000)
    for name in ("一键生成图片", "一键生成视频", "生成事件"):
        button = quick.get_by_role("button", name=name, exact=True)
        expect(button).to_be_visible()
        expect(button).to_have_text("")
        expect(button).to_have_attribute("title", name)
    generate = quick.get_by_role("button", name="生成事件", exact=True)
    expect(generate).to_be_visible(timeout=15000)
    toast = page.locator('.st-key-generation_toasts')
    dialog = page.get_by_role("dialog")
    direction = dialog.get_by_role("textbox", name="用户期望的事件生成方向")
    confirm = dialog.get_by_role("button", name="确认", exact=True)
    skip = dialog.get_by_role("button", name="跳过", exact=True)

    generate.click()
    expect(direction).to_be_visible()
    expect(toast).to_have_count(0)
    direction.fill("  \n  ")
    confirm.click()
    expect(dialog.get_by_text("请输入生成方向，或点击跳过。", exact=True)).to_be_visible()
    expect(toast).to_have_count(0)
    direction.fill("取消时写的草稿")
    dialog.get_by_role("button", name="取消", exact=True).click()
    expect(dialog).to_have_count(0)
    expect(toast).to_have_count(0)
    generate.click()
    expect(direction).to_have_value("")
    direction.fill("跳过时写的草稿")
    skip.click()
    expect(dialog).to_have_count(0)
    expect(toast).to_contain_text("正在生成", timeout=15000)
    expect(toast.get_by_role("button", name="停止任务")).to_be_enabled()
    chat = page.locator('.st-key-page2_chat_input textarea')
    expect(chat).to_be_enabled()
    chat.fill("生成时继续聊天")
    chat.press("Enter")
    expect(page.get_by_text("继续聊天成功。", exact=False)).to_be_visible(timeout=15000)
    expect(toast.get_by_role("button", name="停止任务")).to_have_count(1)
    page.screenshot(path="/tmp/dnd-generation-toast.png")
    toast.get_by_role("button", name="停止任务").click()
    expect(toast).to_have_count(0, timeout=15000)
    page.wait_for_timeout(6500)
    expect(page.locator('[data-testid="stException"]')).to_have_count(0)
    page.get_by_role("button", name="图片与视频", exact=True).click()
    generate.click()
    preferred_direction = "围绕港口失踪案展开。\n增加与旧码头有关的线索。"
    expect(direction).to_have_value("")
    direction.fill(f"  {preferred_direction}\n")
    confirm.click()
    expect(dialog).to_have_count(0)
    expect(toast).to_be_visible(timeout=10000)
    expect(toast).to_have_count(0, timeout=20000)
    game_settings = page.get_by_role("button", name="游戏设置", exact=True)
    game_settings.click()
    page.get_by_role("button", name="查看事件", exact=True).click()
    dialog.locator("summary").filter(has_text="故事背景").click()
    expect(dialog.get_by_role("textbox", name="故事背景", exact=True)).to_have_value(preferred_direction)
    dialog.get_by_role("button", name="取消", exact=True).click()
    expect(dialog).to_have_count(0)
    game_settings.click()
    # Always regenerate prompts, even with an old draft in the editor.
    page.get_by_role("textbox", name="图片prompt（可编辑）", exact=True).fill("旧prompt")
    page.get_by_role("button", name="一键生成图片", exact=True).click()
    expect(toast).to_be_visible(timeout=10000)
    expect(toast).to_have_count(0, timeout=15000)
    expect(page.get_by_role("textbox", name="图片prompt（可编辑）", exact=True)).to_have_count(1)
    expect(page.get_by_role("textbox", name="图片prompt（可编辑）", exact=True)).to_have_value("全新图片prompt", timeout=15000)
    page.get_by_role("button", name="一键生成视频", exact=True).click()
    expect(toast).to_contain_text("一键生成视频", timeout=15000)
    expect(toast).to_have_count(0, timeout=20000)
    expect(page.get_by_role("textbox", name="视频 prompt", exact=True)).to_have_value("全新视频prompt")
    expect(page.locator('[data-testid="stException"]')).to_have_count(0)
    assert not errors, errors
    page.screenshot(path="/tmp/dnd-generation-complete.png")
    # One toast per logical task; stopping the event leaves the image workflow running.
    page.get_by_role("button", name="一键生成图片", exact=True).click()
    generate.click()
    skip.click()
    expect(toast.get_by_role("button", name="停止任务")).to_have_count(2, timeout=10000)
    event_toast = toast.locator('[class*="st-key-generation_toast_"]').filter(has_text="生成事件")
    event_toast.get_by_role("button", name="停止任务").click()
    expect(toast.get_by_role("button", name="停止任务")).to_have_count(1)
    expect(toast).to_have_count(0, timeout=15000)
    # Settings uses the same direct background generation, with no dialog/questions.
    page.goto(URL + "/?view=settings")
    page.wait_for_load_state("networkidle")
    page.get_by_role("button", name="生成事件", exact=True).click()
    expect(page.get_by_role("dialog")).to_have_count(0)
    expect(toast).to_be_visible(timeout=15000)
    expect(toast).to_have_count(0, timeout=20000)
    page.get_by_text("事件", exact=True).click()
    expect(page.get_by_role("textbox", name="故事背景", exact=True)).to_have_value("新故事：商队将在学校附近停留。")
    expect(page.get_by_text("场景事件 · 5条", exact=True)).to_be_visible()
    expect(page.get_by_text("时间事件 · 5条", exact=True)).to_be_visible()
    expect(page.locator('[data-testid="stException"]')).to_have_count(0)
    # Streamlit omits an empty history container; drawers must still open before the first chat.
    empty_page = browser.new_page(viewport={"width": 1440, "height": 1000})
    empty_page.goto(URL + "/?empty=1")
    empty_page.wait_for_load_state("networkidle")
    empty_page.get_by_role("button", name="图片与视频", exact=True).click()
    expect(empty_page.locator("body")).to_have_class(re.compile(r".*dnd-right-open.*"))
    for name in ("一键生成图片", "一键生成视频", "生成事件"):
        expect(empty_page.get_by_role("button", name=name, exact=True)).to_be_visible(timeout=15000)
    empty_page.get_by_role("button", name="图片与视频", exact=True).click()
    expect(empty_page.locator("body")).not_to_have_class(re.compile(r".*dnd-right-open.*"))
    empty_page.close()
    browser.close()
print("PASS: event direction dialog, task toast stop, continued chat, fresh image/video workflows and direct settings events")
